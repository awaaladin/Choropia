// Release signing comes from android/keystore.properties (git-ignored). Without it the release
// build is simply left unsigned instead of failing, so other contributors can still build.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

// Override at build time:  ./gradlew assembleDebug -PchoropiaApi=http://10.0.2.2:8000
val apiOrigin: String = (project.findProperty("choropiaApi") as String?) ?: "https://choropia.vercel.app"
// WebSocket host for live chat/notifications. Empty = the app falls back to REST polling, which
// is what happens on Vercel (serverless can't hold sockets). Point it at the Docker realtime host.
val wsOrigin: String = (project.findProperty("choropiaWs") as String?) ?: ""

android {
    namespace = "com.choropia.app"
    compileSdk = 34

    defaultConfig {
        applicationId = "com.choropia.app"
        minSdk = 26
        targetSdk = 34
        versionCode = 6
        versionName = "1.5.0"

        buildConfigField("String", "API_ORIGIN", "\"$apiOrigin\"")
        buildConfigField("String", "API_BASE_URL", "\"$apiOrigin/api/v1/\"")
        buildConfigField("String", "WS_BASE_URL", "\"$wsOrigin\"")
    }

    signingConfigs {
        if (keystoreProps.containsKey("storeFile")) {
            create("release") {
                storeFile = rootProject.file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            // Minification (R8) is OFF until a release build has been run on a real device: R8 can
            // break serialization/reflection at runtime in ways a compile can't reveal. Turn these
            // two on once verified; proguard-rules.pro already has the rules.
            isMinifyEnabled = false
            isShrinkResources = false
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfigs.findByName("release")?.let { signingConfig = it }
        }
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    composeOptions {
        kotlinCompilerExtensionVersion = "1.5.14"
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
        freeCompilerArgs += listOf(
            "-opt-in=androidx.compose.material3.ExperimentalMaterial3Api",
            "-opt-in=androidx.compose.foundation.ExperimentalFoundationApi",
            "-opt-in=androidx.compose.animation.ExperimentalAnimationApi",
        )
    }

    packaging {
        resources.excludes += "/META-INF/{AL2.0,LGPL2.1}"
    }
}

